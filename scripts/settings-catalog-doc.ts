// Writes docs/SETTINGS-CATALOG.md from the catalogue: npx tsx scripts/settings-catalog-doc.ts
import { writeFileSync } from 'node:fs';
import { CATALOG, catalogCounts, opText, AFTER_TEXT, type Os } from '../core/settings-catalog';
import { CONTROLS } from '../core/appctl';
import { BROWSER_LIMITS } from '../core/browser-tabs';

const OS_NAME: Record<Os, string> = { darwin: 'macOS', win32: 'Windows', linux: 'Linux' };
const esc = (s: string) => s.replace(/\|/g, '\\|').replace(/\n/g, ' ');
const n = catalogCounts();
let md = `# System Settings+ — the settings catalogue

<!-- Generated by scripts/settings-catalog-doc.ts from core/settings-catalog. Do not edit by hand. -->

Keeper by Ashforde® can read and change ${CATALOG.length} system settings that usually need a terminal command or a buried switch
(${n.darwin} on macOS, ${n.win32} on Windows, ${n.linux} on Linux). Open **System → System Settings+**, or type a setting's name in the
command palette.

## How it stays safe

- **Only catalogue operations run.** Each entry describes one operation (a \`defaults\` key, a registry value, a \`gsettings\` key,
  a \`sysctl\`, a service, a power setting…). Keeper builds the command from the entry as an argument list — never a shell line
  typed into the interface — and checks the value first (toggles and choices must be one of the listed values; numbers have
  limits; text cannot contain shell characters).
- **Exact preview.** Before anything changes you see the exact command(s), whether the administrator password is needed and
  what has to restart.
- **Backup first.** Before Keeper first changes an area each day it saves a snapshot: \`defaults export\` (macOS),
  \`reg export\` (Windows), \`gsettings list-recursively\` (Linux). *Backups* lists them with one-click restore.
- **Change log with undo.** Every change (by you, a profile or an AI agent you allowed) is logged with the previous value; *Undo*
  puts it back (or removes Keeper's value so the system default applies).
- **Administrator changes** go through the system's own prompt once per change (pkexec, the macOS password dialog, UAC). Kernel
  parameters are kept in Keeper's own \`/etc/sysctl.d/99-keeper.conf\`.
- **Advice entries** (GRUB, fstab, hosts, swap…) are explained with steps; Keeper reads them but never edits those files.
- **Setup profiles** export the settings you changed to a JSON file; importing shows a preview (what changes, what is already the
  same, what is for another system) and applies only what you tick.
- **AI agents** can search the catalogue (\`system_settings_search\`, allowed by default) and change a setting
  (\`system_settings_change\`, asks every time by default) — permissions in Settings → Abilities. Agent changes are logged and
  can be undone. The \`keeper settings\` command uses the same checks.

`;
for (const os of ['darwin', 'win32', 'linux'] as Os[]) {
  const list = CATALOG.filter((s) => s.os === os);
  md += `## ${OS_NAME[os]} (${list.length})\n\n| Setting | Category | Operation | Admin | Takes effect | Risk |\n|---|---|---|---|---|---|\n`;
  for (const s of list) md += `| **${esc(s.title)}**${s.versions ? ` (${esc(s.versions)})` : ''}<br>${esc(s.description)} | ${s.category} | \`${esc(opText(s))}\` | ${s.admin ? 'yes' : ''} | ${AFTER_TEXT[s.after]} | ${s.risk} |\n`;
  md += '\n';
}
md += `## Per-app controls\n\nOn every app in **App controls**, Applications, Processes and Network Activity (“App settings”).\n\n| Control | macOS | Windows | Linux | Notes |\n|---|---|---|---|---|\n`;
for (const c of CONTROLS) md += `| **${c.title}**<br>${esc(c.description)} | ${c.support.darwin} | ${c.support.win32} | ${c.support.linux} | ${Object.entries(c.notes).map(([k, v]) => `*${OS_NAME[k as Os]}:* ${esc(v!)}`).join('<br>')} |\n`;
md += `\n## Browser tab controls\n\nThrough Keeper's browser extension (\`browser-extension/\`) and the native messaging host (\`keeper browser-host\`). The
extension reports open tabs and what each page talks to; Keeper sends back checked commands (mute, sleep, close, site
permissions, blocking rules built from Keeper's enabled blocklists, clearing site data, per-site proxy as a PAC script). Data and
memory per tab are estimates (from response sizes). Nothing leaves the computer.\n\n| Browser | What works |\n|---|---|\n`;
for (const l of BROWSER_LIMITS) md += `| ${l.browser} | ${esc(l.text)} |\n`;
md += `\n## Sources\n\nEvery entry links its documentation in the app (Details ⓘ). The main references: [ss64 defaults](https://ss64.com/mac/defaults.html),
[macos-defaults.com](https://macos-defaults.com/), [ss64 pmset](https://ss64.com/mac/pmset.html), Microsoft Learn (reg, powercfg, sc, DISM, policy CSPs,
privacy endpoints), the [GNOME admin guide](https://help.gnome.org/admin/system-admin-guide/stable/dconf.html.en),
[kernel sysctl docs](https://docs.kernel.org/admin-guide/sysctl/index.html) and the [systemd manual](https://www.freedesktop.org/software/systemd/man/latest/systemctl.html).\n`;
writeFileSync(new URL('../docs/SETTINGS-CATALOG.md', import.meta.url), md);
console.log(`wrote docs/SETTINGS-CATALOG.md (${CATALOG.length} settings)`);
